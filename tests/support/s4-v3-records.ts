// The acceptance suite also runs against the base, whose trace predates P5.
type AcceptanceTrace = JevTurnTrace & { executed?: (NonNullable<JevTurnTrace['executed']> & { sharedClaimIds?: string[] }) | null };
type ExecutedTrace = AcceptanceTrace & { executed: NonNullable<AcceptanceTrace['executed']> };
/** What one scripted turn answers. `target` is a v3 target label; `issue` answers the repair prospect's issue question. */
export type Plan = { action: string; target: string; issue?: string; prospect?: string; actionScores?: Record<string, number>; speech?: string; inject?: any;
  /** Opt-in override for additional closed questions in independent acceptance tests. */
  choose?: (question: string, criteria: Readonly<Record<string, string>>, context: { generationCalls: number }) => string | undefined;
  speechByLabel?: Partial<Record<Label, string>>;
  failQuestion?: string;
  /** A real human queue event that supersedes the staged candidate before publication. */
  correctionBeforeCommit?: string;
  drafts?: readonly string[];
  draftAct?: DraftAct;
  sharedConstrual?: string;
  failSharedDetail?: true;
  /** Raw JSON text the local-extraction request returns (public name proposals etc.); `act` answers the classifier's `*_act` questions (default assert). */
  extraction?: string; act?: string;
  /** The turn's first decision is a request_observation of figure_0 (one self-side reobservation); `action`/`target` are the terminal decision after it. */
  reobserve?: boolean;
  /** The action question is answered with this label even when it is not offered (a corrupt native response). */
  forceAction?: string;
  /** The name detail question is answered with the candidate whose value is this name (default: the first offered). */
  name?: string;
  /** The classifier's antecedent answer (`claim_0` etc.; default none), for a reply that must be linked to an earlier claim. */
  antecedent?: string;
  /** jev_generation_retry_v12: the classifier's `*_answer` label (default unknown, which reads as no label). */
  answers?: 'answers_checked_point' | 'not_an_answer' | 'unknown';
  /** Raw JSON text the AI-public extraction request returns (the AI's own claims about its public reply); default none. */
  aiExtraction?: string;
  /** Function labels by segment for the AI's public extraction. */
  aiActs?: readonly string[];
  /** The partner-referent estimate's top label (e.g. `multiple`, `figure_3`); default the first offered. */
  referent?: string;
  captureRequest?: (provider: 'luna' | 'jev', body: string) => void };
const TEXTS: Record<string, string> = { local_extraction: '[]', ai_extraction: '[]' };

export async function runTurn(profile: any, label: Label, state: any, events: any[], plan: Plan, technicalTrial: { version: TrialVersion } | undefined, generationRetryVersion?: RecordedGenerationRetryVersion, own = OWN, recordedLabel = label) {
  const issueHandling = isIssueHandlingGeneration(generationRetryVersion);
  const issueHandlingReplayHistory = issueHandling && label !== recordedLabel && state.judgments.length
    ? { strategy: recordedLabel, judgmentCount: state.judgments.length } : undefined;
  const luna: any[] = [], jev: any[] = [], traces: any[] = [], reobservations: any[] = [], boundary = { luna: -1, jev: -1 };
  const httpBodies: { provider: 'luna' | 'jev'; sha256: string }[] = [];
  const capture = (provider: 'luna' | 'jev', init: RequestInit | undefined) => {
    const body = String(init?.body);
    plan.captureRequest?.(provider, body);
    httpBodies.push({ provider, sha256: createHash('sha256').update(body).digest('hex') });
  };
  let next: any, count = 0, actionCalls = 0, generationCalls = 0, lastAction = '';
  const http = createChatClient({ provider: 'cloudflare', apiKey: 'synthetic-offline-replay-key', purpose: profile.modelPolicy.purpose,
    baseUrl: 'http://offline.invalid/v1', timeoutMs: profile.timeouts.lunaAttemptMs },
  async (_url: unknown, init: RequestInit | undefined) => {
    capture('luna', init);
    return Response.json({ model: next.model, choices: [{ message: { content: next.text } }], usage: { prompt_tokens: 0, completion_tokens: 0 } });
  });
  const client = { async complete(messages: any[], options: any) {
    const draft = options.phase === 'generation' ? plan.drafts?.[generationCalls++] : undefined;
    if (options.phase === 'generation' && plan.drafts) assert.ok(draft);
    const response = { text: options.phase === 'local_extraction' && plan.extraction !== undefined ? plan.extraction : options.phase === 'ai_extraction' && plan.aiExtraction !== undefined ? plan.aiExtraction : draft ?? TEXTS[options.phase] ?? plan.speechByLabel?.[label] ?? plan.speech ?? 'もう一度、確かめてみますね。', model: 'synthetic-luna-model', usage: { inputTokens: 0, outputTokens: 0 } };
    luna.push({ phase: options.phase, response }); next = response; return http.complete(messages, options); } };
  const readKey = async () => 'sk-or-SYNTHETIC-offline-replay-key-0000';
  const fetchImpl = async (_url: any, init: any) => {
    capture('jev', init);
    const body = JSON.parse(init.body), answers: any = {};
    if (plan.failSharedDetail && Object.hasOwn(body.questions, 'shared_construal')) return new Response('', {status: 502});
    if (plan.failQuestion && Object.hasOwn(body.questions, plan.failQuestion)) return new Response(null, { status: 502 });
    for (const [key, q] of Object.entries(body.questions) as any) {
      const labels = Object.keys(q.criteria);
      const aiSegment = plan.aiActs && Object.hasOwn(JSON.parse(body.state), 'aiSeq') ? /^segment_(\d+)_act$/u.exec(key) : null;
      const publicAct = aiSegment ? plan.aiActs?.[Number(aiSegment[1])] : undefined;
      if (key === 'action') lastAction = plan.forceAction ?? (plan.reobserve && ++actionCalls === 1 ? 'request_observation' : plan.action);
      const choice = plan.choose?.(key, q.criteria, { generationCalls }) ?? (key === 'action' ? lastAction : key === 'target' ? (lastAction === 'request_observation' ? 'figure_0' : plan.target) : key === 'repair_issue' ? plan.issue ?? 'none' : key === 'prospect' ? plan.prospect ?? 'uncertain'
        : key === 'name' && plan.name ? (labels.find(l => JSON.parse(q.criteria[l]).value === plan.name) ?? labels[0])
        : key === 'human_referent' && plan.referent ? plan.referent
        : key === 'shared_construal' && plan.sharedConstrual ? plan.sharedConstrual
        : key === 'draft_naming' ? (plan.draftAct ?? (plan.action === 'agree' ? 'adopt_chosen' : 'none')) : key === 'basis' ? 'partner_uncertain' : key.endsWith('_antecedent') ? (plan.antecedent ?? 'none') : /^segment_\d+_answer$/u.test(key) ? (plan.answers ?? 'unknown') : key.endsWith('_act') ? (publicAct ?? (plan.act && labels.includes(plan.act) ? plan.act : 'assert')) : key === 'observe_aspect' ? 'orientation' : labels[0]);
      if (!labels.includes(choice) && !(key === 'action' && plan.forceAction)) throw new Error(`scripted choice ${choice} is not offered for ${key}: ${labels.slice(0, 8)}`);
      answers[key] = { type: 'choice', choice, probabilities: Object.fromEntries(labels.map(l => [l, key === 'action' ? plan.actionScores?.[l] ?? (l === choice ? 1 : 0) : l === choice ? 1 : 0])) };
    }
    const response = { model: 'typesafe/jev-1.14', id: 'gen-s4a-' + ++count, usage: { cost: 0 }, answers };
    jev.push(response); return Response.json(response);
  };
  const native = createJevDecisionClient({ enabled: true, readKey, fetchImpl, timeoutMs: profile.timeouts.decisionMs,
    researchLimits: { maxDeadlineMs: 600000 }, questionLayout: profile.questionLayout })!;
  const jevDecision: any = { async decide(input: any, options: any) { if (plan.inject) return structuredClone(plan.inject); const d = await native.decide(input, options);
      if (d.action !== 'request_observation' && boundary.luna === -1) { boundary.luna = luna.length; boundary.jev = jev.length; } return d; },
    completeDetail: (i: any, s: any, o: any) => native.completeDetail!(i, s, o),
    // The partner-referent estimate is asked only for a turn that scripts one (plan.referent), so every other record keeps its request stream.
    ...(plan.referent ? { estimateReferent: (i: any, o: any) => native.estimateReferent!(i, o) } : {}),
    ...(profile.dialoguePolicy ? { classifyDraftAct: (i: any, o: any) => native.classifyDraftAct!(i, o),
      ...(issueHandling ? { classifyDraftSharedClaim: (i: any, o: any) => native.classifyDraftSharedClaim!(i, o) } : {}) } : {}),
    ...(technicalTrial ? { estimateRepairProspect: (i: any, o: any) => native.estimateRepairProspect!(i, o) } : {}) };
  const runtime = createProfileDialogue(profile, { client, image: own.ownImage, anchors: [...own.ownAnchors], strategy: label,
    ...(state.graph?.memoryPruneVersion ? { memoryPruneVersion: state.graph.memoryPruneVersion } : {}),
    observer: { async observeAll() { return structuredClone({ ...OLD.state.observationMemo, figures: OLD.state.observationMemo.figures.filter((f: { id: string }) => own.ownAnchors.some((a: { id: string }) => a.id === f.id)) }); },
      async reobserve(input: any) { const result = { observedAt: '2026-01-01T00:00:01.000Z', issue: structuredClone(input.issue),
        figures: input.figureIds.map((figureId: string) => ({ figureId, supports: ['control-feature'], contradicts: [], unknown: [] })) };
        reobservations.push(structuredClone(result)); await client.complete(buildReobservationMessages(input), { phase: 'observation_targeted' }); return result; } }, jevDecision,
    localGrounding: { classifier: createJevLocalTestClassifier({ enabled: true, readKey, fetchImpl, timeoutMs: profile.timeouts.localMs, researchLimits: { maxDeadlineMs: 600000 }, questionLayout: profile.questionLayout,
      ...(['holistic_v3', 'holistic_v5'].includes(profile.dialoguePolicy) ? { dialoguePolicy: profile.dialoguePolicy } : {}) })!,
      aiPublicTransport: { readKey, fetchImpl, timeoutMs: profile.timeouts.decisionMs } },
    onJevTurnTrace: (t: any) => traces.push(t), generationRetryVersion, ...(technicalTrial ? { technicalTrial } : {}),
    ...(issueHandling ? { deferredAiExtractionProfileSha256: researchHash(profile) } : {}),
    ...(issueHandlingReplayHistory ? { issueHandlingReplayHistory } : {}) } as any);
  const at = '2000-01-01T00:00:00.000Z';
  // Older synthetic callers use speaker-prefixed IDs. The queue restores the
  // same transcript under its own event IDs.
  const queueEvents = events.map(event => ({ ...event, id: `event-${event.seq}`, turn: event.seq, at }));
  const queue = createHumanMessageSequencer({ now: () => Date.parse(at), initialState: {
    events: queueEvents,
    privateState: state, pendingHumanEventIds: [queueEvents.at(-1)!.id], clients: [],
    requestSeq: queueEvents.at(-1)!.seq - 1,
  } as any });
  const request = queue.beginRequest();
  assert.ok(request);
  const publication = () => ({ publicEvents: queue.getSnapshot().events, durable: queue.getDurableState() });
  let result: Awaited<ReturnType<typeof runtime.runAiTurn>>;
  try { result = await runtime.runAiTurn(request); }
  catch (error) {
    const disposition = queue.failRequest(request);
    Object.assign(error as Error, { traces, publication: { ...publication(), status: disposition.status },
      drafts: luna.filter(call => call.phase === 'generation').map(call => call.response.text) });
    throw error;
  }
  assert.ok(boundary.luna >= 0);
  if (plan.correctionBeforeCommit) queue.acceptHuman({ text: plan.correctionBeforeCommit });
  const disposition = queue.completeRequest(request, result);
  const outcome = publication();
  const saved = outcome.durable.privateState;
  const job = saved.deferredAiExtraction;
  if (issueHandling && disposition.status === 'committed' && job) {
    assert.ok('completeDeferredAiExtraction' in runtime && typeof runtime.completeDeferredAiExtraction === 'function');
    assert.equal(job.state, 'queued');
    job.state = 'running';
    const pending = await runtime.completeDeferredAiExtraction(saved, outcome.publicEvents, traces.at(-1).aiPublic);
    assert.notEqual(pending.status, 'failed');
    saved.aiPublic.pending = pending;
    delete saved.deferredAiExtraction;
  }
  const trace = settleJevTurnTraces(traces, saved).at(-1)! as AcceptanceTrace;
  assert.ok(trace.executed, 'a staged v3 candidate has an execution trace');
  const published = disposition.status === 'committed' ? disposition.event ?? null : null;
  return { state: saved, trace: trace as ExecutedTrace, luna, jev, reobservations, boundary, httpBodies,
    candidateText: result.text, speech: published?.text ?? null, publication: { ...outcome, status: disposition.status },
    ...(issueHandling ? { requestSeq: request.requestSeq } : {}) };
}


export type Turn = { human: string; plan: Plan };
/** NORMAL rebuilt as one canonical trial whose final turn follows the earlier scripted turns (all of them under `label`). */
/** dialoguePolicy: omitted = the creation default (holistic_v1); null = the earlier version (no policy), for controls of the older lineages. */
/** The private state a NEW trial of this profile starts from: the cached observation, an optional ledger, and the agreement scope the runtime gives a new trial of its generation version
 * (a new holistic_v5 trial defaults to jev_generation_retry_v8, whose scope is scoped_v5). A test that pins an older version passes it. */
export function initialState({ profile, ledger, memo, generationRetryVersion, agreeNameScopeVersion }: { profile: any; ledger?: Record<string, any>; memo?: ObservationMemo;
  generationRetryVersion?: RecordedGenerationRetryVersion; agreeNameScopeVersion?: AgreeNameScopeVersion }) {
  const state: any = structuredClone(OLD.state); if (ledger) state.ledger = structuredClone(ledger);
  state.interventionPolicy = structuredClone(profile.interventionPolicy);
  const created = generationRetryVersion ?? (profile.dialoguePolicy === 'holistic_v5' ? defaultGenerationRetryVersion('two_stage_v3', 'holistic_v5') : undefined);
  const scope = agreeNameScopeVersion ?? (isGenerationV11(created) ? 'scoped_v6' : isGenerationV8(created) ? 'scoped_v5' : isGenerationV7(created) ? 'scoped_v4' : isGenerationV6(created) ? 'scoped_v3' : undefined);
  if (scope) state.agreeNameScopeVersion = scope;
  if (memo) state.observationMemo = structuredClone(memo);
  return state;
}
/** A turn in which the AI publicly describes one figure it also acts on (an accept with a public claim about it): the public basis a later naming turn needs under the v6 agreement scope. */
export function publicFocusTurn(figureIndex = 0): Turn {
  const text = '輪が台に接している形です。';
  return { human: 'この形の特徴を教えてください。', plan: { action: 'accept', target: 'figure_' + figureIndex, referent: 'figure_' + figureIndex, speech: text,
    aiExtraction: JSON.stringify([{ segmentId: 's1', quote: text, proposition: text, name: null, targets: [OWN.ownAnchors[figureIndex].id], aspect: 'part', linkedIssueId: null, respondsToTurn: null }]) } };
}
export async function buildRecords({ label = 'repair-first' as Label, technicalTrial, turns, ledger, dialoguePolicy, memo, generationRetryVersion, agreeNameScopeVersion, onTurn, promptSources, interventionVersion, judgmentMaterialVersion, figureCount = 6 }: {
  label?: Label; technicalTrial?: { version: TrialVersion }; turns: Turn[]; ledger?: Record<string, any>; dialoguePolicy?: DialoguePolicy | null; memo?: ObservationMemo; generationRetryVersion?: RecordedGenerationRetryVersion;
  agreeNameScopeVersion?: AgreeNameScopeVersion;
  onTurn?: (label: Label, result: Awaited<ReturnType<typeof runTurn>>) => void;
  promptSources?: Awaited<ReturnType<typeof promptSourceManifest>>;
  interventionVersion?: Parameters<typeof researchTrialProfileV3>[4];
  judgmentMaterialVersion?: JudgmentMaterialVersion;
  figureCount?: 4 | 6;
}) {
  const n = structuredClone(normal), tr = n.trials[0], m = n.run.manifest;
  const own = { ...OWN, ownAnchors: OWN.ownAnchors.slice(0, figureCount) };
  await bindCurrentS4PromptSources(n, promptSources);
  const profile = JSON.parse(JSON.stringify(researchTrialProfileV3(m.lunaRequest, m.timeouts, 'two_stage_v3', dialoguePolicy, interventionVersion, judgmentMaterialVersion)));
  const digest = hash(profile);
  for (const s of [n.run, n.summary, tr]) { s.profile = structuredClone(profile); s.profileSha256 = digest; }
  tr.identity.profile = digest; tr.label = label; m.trials[0].label = label; n.summary.runOrder[0].label = label;
  let state: any = initialState({ profile, ledger, memo, generationRetryVersion, agreeNameScopeVersion });
  if (figureCount === 4) {
    const slots = own.ownAnchors.map((anchor: { id: string }) => anchor.id);
    state.ledger = Object.fromEntries(slots.map((slot: string) => [slot, state.ledger[slot]]));
    state.graph.slots = slots;
    state.observationMemo.figures = state.observationMemo.figures.filter((figure: { id: string }) => slots.includes(figure.id));
  }
  let events: any[] = [];
  for (let i = 0; i < turns.length; i++) {
    const seq = events.length + 1;
    events = [...events, { id: `event-${seq}`, seq, speaker: 'human', text: turns[i].human }];
    const run = { state, events: structuredClone(events) };
    const last = i === turns.length - 1;
    if (!last) {
      const r = await runTurn(profile, label, state, events, turns[i].plan, technicalTrial, generationRetryVersion, own);
      assert.equal(r.publication.status, 'committed');
      onTurn?.(label, r);
      state = r.state;
      events = r.publication.publicEvents.map(({ id, seq, speaker, text }) => ({ id, seq, speaker, text }));
      continue;
    }
    // The final turn is run once per label: the common segment (before the original decision) is shared, each tail is that label's own.
    const runs = { 'repair-first': await runTurn(profile, 'repair-first', run.state, run.events, turns[i].plan, technicalTrial, generationRetryVersion, own, label),
      'bypass-enabled': await runTurn(profile, 'bypass-enabled', run.state, run.events, turns[i].plan, technicalTrial, generationRetryVersion, own, label) };
    const a = runs['repair-first'], b = runs['bypass-enabled'];
    assert.equal(a.publication.status, 'committed');
    assert.equal(b.publication.status, 'committed');
    onTurn?.('repair-first', a);
    onTurn?.('bypass-enabled', b);
    assert.deepEqual([a.luna.slice(0, a.boundary.luna), a.jev.slice(0, a.boundary.jev)], [b.luna.slice(0, b.boundary.luna), b.jev.slice(0, b.boundary.jev)]);
    assert.deepEqual(a.reobservations, b.reobservations);
    const seg = (r: any) => ({ luna: r.luna.slice(r.boundary.luna), jev: r.jev.slice(r.boundary.jev), reobservations: [] });
    const version = runs[label].trace.generationRetryVersion ?? generationRetryVersion;
    const tape: any = { schemaVersion: 'parity_intervention_replay_v1', state: run.state, events: run.events,
      common: { luna: a.luna.slice(0, a.boundary.luna), jev: a.jev.slice(0, a.boundary.jev), reobservations: structuredClone(a.reobservations) },
      tails: { 'repair-first': seg(a), 'bypass-enabled': seg(b) }, recorded: { label, expectedRequests: [] }, ...(technicalTrial ? { technicalTrial } : {}),
      ...(version ? { generationRetryVersion: version } : {}),
      ...(isIssueHandlingGeneration(version) ? { requestSeq: runs[label].requestSeq } : {}) };
    const probe: any = await pairedInterventionReplay(tape, own as any, MODEL, profile);
    assert.equal(probe.status === 'not_reached', false, String(probe.error));
    const recorded = probe.sides.find((s: any) => s.label === label);
    tape.recorded.expectedRequests = recorded.requests.map((r: any, k: number) => ({ provider: r.provider, phase: r.phase, requestSha256: r.preProjectionPayloadSha256,
      actualSendMeasured: true, sendIds: [k + 1], ...(r.provider === 'luna' ? { messagesSha256: r.completeMessagesSha256 } : {}) }));
    const result: any = await pairedInterventionReplay(tape, own as any, MODEL, profile);
    assert.equal(result.status, 'same_material_intervention_verified', String(result.error));
    const { trace, state: after } = runs[label];
    // The record keeps its own run's intervention, including the measured latency of the alternative's detail evidence (audit/06 R2).
    const template = (provider: string) => normal.trials[0].calls.find((c: any) => c.provider === provider);
    const turn = trace.turnIndex;
    tr.calls = recorded.requests.map((r: any, k: number) => ({ ...structuredClone(template(r.provider)), id: k + 1, sendIds: [k + 1], phase: r.phase, turn,
      requestSha256: r.provider === 'luna' ? r.completeMessagesSha256 : r.preProjectionPayloadSha256,
      ...(r.provider === 'luna' ? { expectedHttpRequestSha256: r.preProjectionPayloadSha256, httpRequestSha256: r.preProjectionPayloadSha256 } : {}) }));
    tr.http = recorded.requests.flatMap((r: any, k: number) => r.provider === 'luna' ? [{ method: 'POST', kind: 'completion_post', phase: r.phase, callId: k + 1, sendId: k + 1,
      hashScheme: 'canonical_json_sha256', requestSha256: r.preProjectionPayloadSha256, status: 200, outcome: 'returned' }] : []);
    tr.attempts = [trace];
    tr.turns = [{ ...structuredClone(tr.turns[0]), turn, publicText: runs[label].speech, trace: [structuredClone(trace)], state: structuredClone(after) }];
    tr.lastCommittedState = structuredClone(after); tr.replay = [{ tape, result }];
    n.evidence.pairedReplay = [{ trialOrder: 0, turn, left: result.sides[0], right: result.sides[1] }];
  }
  return JSON.parse(JSON.stringify(n));
}
